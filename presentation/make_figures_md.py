#!/usr/bin/env python3
"""Generate presentation/FIGURES.md. Tables are emitted from the same JSON the
figures use, so nothing is hand-transcribed."""
from __future__ import annotations
import collections, json, os, statistics as st, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
os.chdir(ROOT); sys.path.insert(0, HERE)
C = json.load(open(f"{HERE}/corpus_stats.json"))
T = json.load(open(f"{HERE}/token_stats.json"))
M = json.load(open(f"{HERE}/model_stats.json"))
GOLD = [json.loads(l) for l in open("classifier/data/humset_gold.jsonl")]
R2_PATH = "classifier/data/annot-thin/labels-HsuLinHtet.jsonl"
R2 = [r for r in (json.loads(l) for l in open(R2_PATH))
      if r.get("annotator") == "HsuLinHtet"]
assert len(R2) == 360, f"round 2 should be complete at 360, got {len(R2)}"
THIN = {json.loads(l)["url"]: json.loads(l)
        for l in open("classifier/data/humset_thin_task.jsonl")}
GOLDL = {r["url"]: set(r["labels"]) for r in GOLD}
IAA = [json.loads(l) for l in open("classifier/data/annot-iaa2/labels-ZweHtetAung.jsonl")]
assert len(IAA) == 50, len(IAA)
IAA_EXACT = sum(1 for r in IAA if set(r["labels"]) == GOLDL[r["url"]]) / len(IAA)
IAA_JAC = st.mean(len(set(r["labels"]) & GOLDL[r["url"]])
                  / len(set(r["labels"]) | GOLDL[r["url"]]) for r in IAA)

OUT = {"dvb": "DVB", "irrawaddy": "Irrawaddy", "bbc": "BBC",
       "myanmarnow": "Myanmar Now", "rfa": "RFA"}
ORDER = ["context", "shock_event", "casualties", "other", "displacement",
         "humanitarian_access", "information_communication"]
seeds = [M[f"xlmr_seed{s}"]["macro_sup"] for s in (20261015, 20261016, 20261017)]
g = C["global"]
gc_ = collections.Counter(l for r in GOLD for l in r["labels"])
r2c = collections.Counter(l for r in R2 for l in r["labels"])

L = []
w = L.append
w("# Presentation figures\n")
w("Generated by `presentation/make_figures.py` (charts) and")
w("`presentation/make_figures_md.py` (this file). Regenerate both with:\n")
w("```\n.venv/bin/python presentation/corpus_stats.py     # recompute the funnel from data-vm/")
w(".venv/bin/python presentation/token_stats.py      # recompute XLM-R token counts")
w(".venv/bin/python presentation/model_stats.py      # recompute metrics from dumps + checkpoints")
w(".venv/bin/python presentation/make_figures.py")
w(".venv/bin/python presentation/make_figures_md.py\n```\n")
w("All PNGs are 300 dpi on a light background, sized for 16:9 slides.\n")

w("## Where the numbers come from\n")
w("| Source | Used for |")
w("|---|---|")
w("| `presentation/corpus_stats.json` | **Recomputed** from `data-vm/*/parsed/articles.jsonl`, "
  "replicating `classifier/build_dataset.py`'s filter order exactly. Figures 1, 2, 3. |")
w("| `presentation/token_stats.json` | **Recomputed** with the `xlm-roberta-base` tokenizer "
  "over the same 383 articles `train_xlmr.py` loads. Figure 4. |")
w("| `presentation/model_stats.json` | **Recomputed** from `humset_tfidf_cv.jsonl` and the four "
  "`xlmr_ckpt*.json` checkpoints, using `train_humset.prf`/`repair`/`MIN_SUPPORT`. No training. Figures 9, 11. |")
w("| `classifier/data/humset_gold.jsonl` | Read directly. Figures 5, 6, 7, 8, 11. |")
w("| round-2 labels (360 rows) | Read directly, filtered to `annotator == \"HsuLinHtet\"`. Figure 7. |")
w("| `README.md` | **Transcribed**, only where the generating script is not in the repo: "
  "the learning curve (L1477-1480), the weak-supervision dose-response (L1602-1608), and the "
  "matched-input TF-IDF column (L1744-1756). Figures 8, 10, 11, and TF-IDF's 0.727 in figure 9. |")
w("")
w("Every recomputed number was checked against the README and agrees. The one apparent "
  "conflict is explained below.\n")

w("### The 38,009 vs 38,093 reconciliation\n")
w("The README quotes both numbers and both are right -- they are different filters, "
  "and the figures use **38,009** throughout:\n")
w("```")
w(f"build_dataset.py   NFC-normalise + strip, then <200 drop, plus exact-body dedup -> {g['kept']:,}")
w(f"prelabel_llm.py    raw body length, no body dedup                               -> 38,093")
w(f"difference         {g['dup_body']} duplicate bodies + 1 article >=200 raw but <200 stripped = {g['dup_body']+1}")
w("```")
w("38,009 is the model-ready corpus; 38,093 was only ever used for an API cost estimate.\n")

w("---\n")
figs = [
 ("fig01_pipeline.png", "The pipeline, with the counts that survive each stage",
  f"Collect {g['read']:,} -> Clean {g['kept']:,} -> Label 383 (+360) -> Classify -> Retrieve. "
  "Stage 5 is drawn dashed because the RAG arm is not built yet.",
  "Recomputed. Stage 4's 0.727 is README-transcribed (see above)."),
 ("fig02_outlet_composition.png", "Corpus composition and where cleaning losses land",
  f"DVB is {26103/g['kept']:.1%} of the corpus. Cleaning losses concentrate in RFA "
  "(110 of 143), almost all duplicate programme boilerplate.", "Recomputed."),
 ("fig03_corpus_timeline.png", "Collection volume by month, stacked by outlet",
  "Sep 2026 is a partial month (the crawl ends 26 Sep) and is annotated as such. "
  "RFA's share collapses after Apr 2025 -- a real collection pattern, not a cleaning artefact.",
  "Recomputed. Table view below (the palette's 5-slot contrast WARN requires it)."),
 ("fig04_token_cliff.png", "XLM-R cannot read 60% of these articles",
  f"{T['truncated']}/{T['n']} articles ({T['truncated_frac']:.1%}) exceed the 512-token limit; "
  f"{T['tokens_discarded']:,} of {T['tokens_total']:,} tokens ({T['tokens_discarded_frac']:.1%}) are discarded. "
  "The 512 cap is architectural, not a setting.", "Recomputed."),
 ("fig05_label_distribution.png", "Label distribution and multi-label structure",
  f"Two of seven labels sit under 20 positives. {sum(1 for r in GOLD if len(r['labels'])>1)/len(GOLD):.0%} "
  f"of articles carry more than one label (mean {sum(len(r['labels']) for r in GOLD)/len(GOLD):.2f}).",
  "Computed from humset_gold.jsonl."),
 ("fig06_label_cooccurrence.png", "Which labels travel together",
  "All 85 `casualties` articles are also `shock_event`. The empty `Other` row and column is the "
  "exclusivity rule holding: `other` never co-occurs.", "Computed from humset_gold.jsonl."),
 ("fig07_thin_label_fix.png", "Targeted sampling moved both thin labels past the floor",
  f"humanitarian_access {gc_['humanitarian_access']} -> {gc_['humanitarian_access']+r2c['humanitarian_access']}, "
  f"information_communication {gc_['information_communication']} -> {gc_['information_communication']+r2c['information_communication']}. "
  "**Round 2 is an enriched sample; its hit rates are not corpus prevalence.**",
  "Computed from the 360-row round-2 file + humset_gold.jsonl."),
 ("fig08_learning_curve.png", "The two zeros are a data-quantity result",
  "Every label collapses toward 0.00 at k=5, including the easiest. F1~0.5 needs ~30 positives. "
  "The red rules mark the two thin labels' actual support (6 and 16).",
  "README-transcribed (L1477-1480); support counts computed."),
 ("fig09_model_comparison.png", "TF-IDF vs XLM-R on matched input",
  f"0.727 vs {st.mean(seeds):.3f} (3 seeds, sd {st.stdev(seeds):.3f}); gap "
  f"{0.727-st.mean(seeds):.3f} = {(0.727-st.mean(seeds))/st.stdev(seeds):.1f}x the seed noise. "
  "The full-text 0.755 is named in the subtitle and explicitly excluded as the comparison point.",
  "XLM-R recomputed from checkpoints; TF-IDF 0.727 README-transcribed."),
 ("fig10_weak_supervision.png", "Weak supervision made it worse, in proportion to volume",
  "0.755 -> 0.702 as the weak pool grows to 16,087. The x-axis is categorical and labelled "
  "'not drawn to scale', because the pool sizes are not evenly spaced.",
  "README-transcribed (L1602-1608)."),
 ("fig11_per_label_matched.png", "Per-label F1, matched input, with seed error bars",
  "TF-IDF leads on all five measurable labels. XLM-R is the only arm non-zero on "
  "humanitarian_access, but at 16 positives with sd comparable to the mean that is a signal "
  "of shape, not a measurement. The two thin labels are shaded out.",
  "XLM-R recomputed; TF-IDF matched column README-transcribed."),
 ("fig12_annotation_ceiling.png", "The ceiling set by annotation agreement",
  f"50 gold articles re-labelled blind by a second annotator: exact set match {IAA_EXACT:.3f}, "
  f"Jaccard {IAA_JAC:.3f} (mean per article, matching score_multilabel.py). Per-label F1 of the "
  "second annotator sits beside the model's. On Context and Casualties the model is AT the human "
  "level; on Shock/Event and Displacement it is above it. That is convention-learning, not "
  "competence: the model was fitted to these labels through CV and a second annotator was not, "
  "so the figure is captioned as a ceiling and explicitly NOT as a model beating a human. "
  "`other` and `information_communication` are excluded -- the second annotator had already seen "
  "all 85 pass-1 `other` articles, so no unseen sample can contain one. IAA run 1 is NOT plotted "
  "anywhere: it was served while the guide still named the under-represented labels and measures "
  "that priming (+23/-0 on humanitarian_access) rather than agreement.",
  "Agreement recomputed from classifier/data/annot-iaa2/; model F1 recomputed from the TF-IDF dump."),
]
for f, cap, detail, src in figs:
    w(f"### `{f}`\n")
    w(f"**{cap}**\n")
    w(f"{detail}\n")
    w(f"*Numbers:* {src}\n")
w("---\n")

w("## Table views\n")
w("The 5-slot categorical palette passes every CVD gate but three slots fall below 3:1 "
  "contrast on a light surface, so the skill's relief rule applies: these tables are the "
  "accessible twin of figures 3 and 11.\n")
w("### Figure 3 -- articles per month per outlet\n")
sites = sorted(C["per_site"], key=lambda s: -C["per_site"][s]["kept"])
w("| Month | " + " | ".join(OUT[s] for s in sites) + " | Total |")
w("|" + "---|" * (len(sites) + 2))
for m in sorted(C["months"]):
    row = [C["months_by_site"][s].get(m, 0) for s in sites]
    star = " *" if m == "2026-09" else ""
    w(f"| {m}{star} | " + " | ".join(f"{v:,}" for v in row) + f" | {sum(row):,} |")
w(f"| **Total** | " + " | ".join(f"**{C['per_site'][s]['kept']:,}**" for s in sites)
  + f" | **{g['kept']:,}** |")
w("\n\\* partial month: the crawl ends 2026-09-26.\n")

w("### Figure 11 -- per-label F1\n")
sk = [f"xlmr_seed{s}" for s in (20261015, 20261016, 20261017)]
RM = {"context": .810, "shock_event": .861, "casualties": .733, "other": .760,
      "displacement": .472, "humanitarian_access": .000,
      "information_communication": .000}
w("| Label | Positives | TF-IDF (matched) | XLM-R mean | XLM-R sd | seeds |")
w("|---|---:|---:|---:|---:|---|")
for l in ORDER:
    v = [M[k]["per_label"][l]["F1"] for k in sk]
    w(f"| {l} | {gc_[l]} | {RM[l]:.3f} | {st.mean(v):.3f} | {st.stdev(v):.3f} | "
      + ", ".join(f"{x:.3f}" for x in v) + " |")
w(f"| **macro-F1 (support >= 20)** | | **0.727** | **{st.mean(seeds):.3f}** | "
  f"**{st.stdev(seeds):.3f}** | " + ", ".join(f"{x:.3f}" for x in seeds) + " |")
w("")

w("### Round 2 -- hit rate by targeted stratum\n")
w("| Target label | Served | Hit | Rate | New positives |")
w("|---|---:|---:|---:|---:|")
for t in ("humanitarian_access", "information_communication"):
    sub = [r for r in R2 if THIN[r["url"]]["_targeted_for"] == t]
    hit = sum(1 for r in sub if t in r["labels"])
    w(f"| {t} | {len(sub)} | {hit} | {hit/len(sub):.1%} | {r2c[t]} |")
w("\n**These rates describe the enriched sample only.** The ranker selected these 360 "
  "articles, so recall is optimistic (easy positives) and precision pessimistic (hard "
  "negatives); the net direction is indeterminate. Never quote them as corpus prevalence.\n")

w("## Caveats worth repeating on the slides\n")
w("1. **0.727, not 0.755.** XLM-R reads only the first 512 tokens, so the matched-input "
  "control is the comparison. Figure 9 says so in its subtitle.")
w("2. **The thin labels are not measured.** 16 and 6 positives. Figures 5, 8 and 11 all "
  "mark them rather than reporting them as results.")
w("3. **Round 2 is enriched, not representative.** Figure 7 and the table above say so.")
w("4. **One annotator.** All 383 gold labels and all 360 round-2 labels come from a single "
  "annotator (pass 2 on 85 `other` articles was a second person). There is no "
  "inter-annotator agreement figure yet, so no figure claims reliability.")
w("5. **Seed noise.** XLM-R per-label F1 carries roughly +-0.05; figure 11 shows error bars.")
w("6. **Sep 2026 is partial.** Figure 3 annotates it.\n")
open(f"{HERE}/FIGURES.md", "w").write("\n".join(L))
print(f"wrote presentation/FIGURES.md ({len(L)} lines)")
